#!/usr/bin/env node
// Writes docs/superpowers/inventory/module-map.md: one table per directory under src/, one row per module
// (path, exports, purpose). Seam facades (seam-*.js) are listed as one row per directory.
//
//   node scripts/module-map.js                   write the file (only with no flag)
//   node scripts/module-map.js --check           exit 1 if the file is stale; writes nothing
//   node scripts/module-map.js --require-purpose exit 1 if a core/ or ui/ module (not a seam facade) has no purpose comment;
//                                                writes nothing (`npm test` runs `--check --require-purpose`)
//   --root DIR                                   run on another tree (default: this repository; tests/module_map.js)
//
// A module's purpose is line 1 when it is a `//` comment that does not start with `// load-time:` and line 2 is blank.
// Line endings are ignored when comparing (the working tree is CRLF).
const fs = require('fs');
const path = require('path');
const espree = require('espree');
const { isUi, isCore, isFacade } = require('./lib/src-paths');

const argv = process.argv.slice(2);
const rootAt = argv.indexOf('--root');
if (rootAt >= 0 && (rootAt + 1 >= argv.length || argv[rootAt + 1].startsWith('--'))) {
  console.error('module-map.js: --root needs a directory');
  process.exit(2);
}
const root = rootAt >= 0 ? path.resolve(argv[rootAt + 1]) : path.join(__dirname, '..');
const args = rootAt >= 0 ? argv.filter((_, i) => i !== rootAt && i !== rootAt + 1) : argv;
const SRC = path.join(root, 'src');
const OUT = path.join(root, 'docs', 'superpowers', 'inventory', 'module-map.md');
const NO_PURPOSE = '(no purpose comment)';
const norm = (s) => s.replace(/\r\n/g, '\n');
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function walk(dir, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name !== 'node_modules') walk(p, out);
    } else if (e.name.endsWith('.js')) out.push(p);
  }
  return out;
}

function patternNames(p, out) {
  if (!p) return;
  if (p.type === 'Identifier') out.push(p.name);
  else if (p.type === 'ObjectPattern') p.properties.forEach((q) => patternNames(q.type === 'RestElement' ? q.argument : q.value, out));
  else if (p.type === 'ArrayPattern') p.elements.forEach((q) => patternNames(q, out));
  else if (p.type === 'RestElement') patternNames(p.argument, out);
  else if (p.type === 'AssignmentPattern') patternNames(p.left, out);
}

function exportsOf(code) {
  const ast = espree.parse(code, { ecmaVersion: 2022, sourceType: 'module' });
  const names = [];
  for (const n of ast.body) {
    if (n.type === 'ExportNamedDeclaration') {
      const d = n.declaration;
      if (d) {
        if (d.type === 'VariableDeclaration') d.declarations.forEach((x) => patternNames(x.id, names));
        else names.push(d.id.name);
      }
      for (const s of n.specifiers) names.push(s.exported.name || s.exported.value);
    } else if (n.type === 'ExportDefaultDeclaration') names.push('default');
    else if (n.type === 'ExportAllDeclaration') names.push(n.exported ? `* as ${n.exported.name}` : `* from ${n.source.value}`);
  }
  return names.sort();
}

function purposeOf(code) {
  const lines = norm(code).split('\n');
  const l1 = lines[0];
  if (/^\/\//.test(l1) && !/^\/\/\s*load-time:/.test(l1) && lines.length > 1 && lines[1].trim() === '') {
    return l1.replace(/^\/\/\s?/, '').trim() || NO_PURPOSE;
  }
  return NO_PURPOSE;
}

function build() {
  const files = walk(SRC, []).map((p) => path.relative(root, p).split(path.sep).join('/')).sort();
  const dirs = new Map();
  const offenders = [];
  for (const rel of files) {
    const dir = path.posix.dirname(rel);
    const base = path.posix.basename(rel);
    const code = fs.readFileSync(path.join(root, rel), 'utf8');
    let names;
    try {
      names = exportsOf(code);
    } catch (e) {
      throw new Error(`${rel}: ${e.message}`);
    }
    const purpose = purposeOf(code);
    if (!dirs.has(dir)) dirs.set(dir, { modules: [], seams: [] });
    const entry = dirs.get(dir);
    if (/^seam-.*\.js$/.test(base)) entry.seams.push(...names);
    else {
      entry.modules.push({ rel, names, purpose });
      if ((isUi(rel) || isCore(rel)) && !isFacade(rel) && purpose === NO_PURPOSE) offenders.push(rel);
    }
  }
  const lines = [
    '# Module map',
    '',
    'Generated by `node scripts/module-map.js` (run by `npm run analyze`); do not edit by hand. One table per directory under `src/`; seam facades (`seam-*.js`) are one row per directory.',
    '',
  ];
  let moduleRows = 0;
  let seamRows = 0;
  for (const dir of [...dirs.keys()].sort()) {
    const { modules, seams } = dirs.get(dir);
    lines.push(`## ${dir}`, '', '| Module | Exports | Purpose |', '| --- | --- | --- |');
    for (const m of modules) {
      lines.push(`| \`${m.rel}\` | ${m.names.length ? cell(m.names.join(', ')) : '(none)'} | ${cell(m.purpose)} |`);
      moduleRows++;
    }
    if (seams.length) {
      lines.push(`| \`seam-*.js\` | ${cell([...new Set(seams)].sort().join(', '))} | (seam facade) |`);
      seamRows++;
    }
    lines.push('');
  }
  return { text: lines.join('\n'), offenders, moduleRows, seamRows };
}

const bad = args.filter((a) => a !== '--check' && a !== '--require-purpose');
if (bad.length) {
  console.error(`module-map.js: unknown argument ${bad.map((a) => `'${a}'`).join(', ')}; expected --check and/or --require-purpose, and optionally --root <dir>`);
  process.exit(2);
}
const { text, offenders, moduleRows, seamRows } = build();
let failed = false;
if (args.includes('--check')) {
  const have = fs.existsSync(OUT) ? norm(fs.readFileSync(OUT, 'utf8')) : null;
  if (have !== text) {
    console.error('module-map.md is stale; run npm run analyze');
    failed = true;
  }
} else if (!args.length) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`module-map.md: ${moduleRows} module rows, ${seamRows} facade rows`);
}
if (args.includes('--require-purpose') && offenders.length) {
  console.error(`core/ and ui/ modules without a purpose comment (${offenders.length}):\n  ` + offenders.join('\n  '));
  failed = true;
}
process.exit(failed ? 1 : 0);
