#!/usr/bin/env node
// Generates docs/province-tax-rules.md, the review artifact for the Canadian provincial tax table, from the
// PROVINCE_RULES block in Planner_Canada.html (between the `PROVINCE_RULES:begin` / `end` comments, which
// holds pure literals). One row per province with every rule and its source.
//
//   node scripts/gen-province-rules.js           write docs/province-tax-rules.md
//   node scripts/gen-province-rules.js --check   exit 1 if the file is stale (run by `npm test`)
//
// Not needed to run the planner. Line endings are ignored when comparing (the working tree is CRLF).
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const PLANNER = path.join(root, 'Planner_Canada.html');
const OUT = path.join(root, 'docs', 'province-tax-rules.md');
const norm = (s) => s.replace(/\r\n/g, '\n');

function loadRules() {
  const html = norm(fs.readFileSync(PLANNER, 'utf8'));
  const a = html.indexOf('// PROVINCE_RULES:begin'),
    b = html.indexOf('// PROVINCE_RULES:end');
  if (a < 0 || b < a) throw new Error('PROVINCE_RULES markers not found in Planner_Canada.html');
  return vm.runInNewContext(html.slice(a, b) + '\nPROVINCE_RULES;');
}

const money = (n) => '$' + Number(n).toLocaleString('en-US');
const pct = (r) => +(r * 100).toFixed(4) + '%';
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function indexingText(ix) {
  const on = Object.entries(ix).filter(([, v]) => v).map(([k]) => k.replace(/Indexed$/, ''));
  const off = Object.entries(ix).filter(([, v]) => !v).map(([k]) => k.replace(/Indexed$/, ''));
  if (!off.length) return 'all indexed';
  if (!on.length) return 'none indexed';
  return `indexed: ${on.join(', ')}; not indexed: ${off.join(', ')}`;
}
function bpaText(b) {
  return money(b.amount) + (b.phase ? ` (reduced to ${money(b.phase.floor)} between ${money(b.phase.start)} and ${money(b.phase.end)} net income)` : '');
}
function ageText(a, pooled) {
  if (!a && pooled) return 'pooled with the retirement-income and living-alone amounts (see Quebec below)';
  if (!a) return 'not modeled';
  return `${money(a.amount)}, reduced ${pct(a.rate)} of net income over ${money(a.threshold)}` + (a.supplement ? `, plus ${money(a.supplement)} supplement (not reduced)` : '');
}
function verifiedText(v) {
  return Object.entries(v).map(([k, s]) => `${k}: ${s}`).join(', ');
}

function generate(rules) {
  const codes = Object.keys(rules);
  const L = [];
  L.push('# Provincial income tax rules (generated)');
  L.push('');
  L.push('Generated by `node scripts/gen-province-rules.js` from `PROVINCE_RULES` in `Planner_Canada.html`; do not edit by hand.');
  L.push('`npm test` fails if this file is stale. Amounts are 2026 dollars. Each row says, per family, whether its figures were read on a');
  L.push('primary page (a province or CRA page) or only on a secondary one (TaxTips and similar); see the Batch 7 notes in docs/next-batches-plan.md.');
  L.push('');
  L.push(`${codes.length} provinces (the three territories are out of scope).`);
  L.push('');
  L.push('**Credits.** Every non-refundable amount is worth the province\'s lowest bracket rate (`creditRate`) and comes off the tax, floored at zero.');
  L.push('Provincial credits never reduce federal tax and the reverse. **Not modeled (documented gaps):** non-eligible Canadian dividends (taxed like interest),');
  L.push('spouse and eligible-dependant amounts, the transfer of a spouse unused amounts, paid benefits (7L), and territorial taxes.');
  L.push('');
  L.push('## Rules');
  L.push('');
  L.push('| Code | Province | Credit rate | Basic personal amount | Age amount | Pension amount | Eligible dividend credit | Surtax / premium | Pension plan contribution | Indexing | Sources |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const c of codes) {
    const r = rules[c];
    const extra = [r.surtax ? `surtax ${pct(r.surtax.firstRate)} over ${money(r.surtax.first)}, ${pct(r.surtax.secondRate)} over ${money(r.surtax.second)}` : '', r.healthPremium ? 'income-tested health premium (up to $900)' : ''].filter(Boolean).join('; ') || 'none';
    L.push(
      '| ' +
        [
          c.toUpperCase(),
          r.name,
          pct(r.creditRate),
          bpaText(r.bpa),
          ageText(r.age, r.pooled),
          r.pension ? money(r.pension.amount) : r.pooled ? `retirement income ${money(r.pooled.retirementAmount)} (pooled)` : 'not modeled',
          pct(r.dividend.eligible) + ' of the grossed-up dividend',
          extra,
          (r.pooled ? 'QPP ' : 'CPP ') + pct(r.payroll.pensionRate) + (r.payroll.premium ? ` + QPIP ${pct(r.payroll.premium.rate)} up to ${money(r.payroll.premium.max)}` : ''),
          indexingText(r.indexing),
          `[${r.asOf}, retrieved ${r.retrieved}](${r.source})${r.amountsSource !== r.source ? `; amounts: [${r.amountsSource}](${r.amountsSource})` : ''}; ${verifiedText(r.verified)}`,
        ]
          .map(cell)
          .join(' | ') +
        ' |',
    );
  }
  L.push('');
  L.push('## Quebec pooled amounts');
  L.push('');
  for (const c of codes) if (rules[c].pooled) { const p = rules[c].pooled; L.push(`- **${c.toUpperCase()}**: age ${money(p.ageAmount)} (65+), retirement income up to ${money(p.retirementAmount)}, living alone ${money(p.livingAlone)} (single filers and survivors); the total is reduced by ${pct(p.reductionRate)} of family net income over ${money(p.reductionThreshold)}, then taken at the credit rate.`); }
  L.push('');
  L.push('## Notes');
  L.push('');
  for (const c of codes) if (rules[c].notes) L.push(`- **${c.toUpperCase()}**: ${rules[c].notes}`);
  L.push('');
  L.push('## Brackets');
  L.push('');
  L.push('Upper limit of each bracket and its rate; the last bracket is open-ended.');
  L.push('');
  for (const c of codes) {
    const r = rules[c];
    L.push(`- **${c.toUpperCase()}** ${r.name}: ` + r.brackets.map(([cap, rate]) => `${cap === Infinity ? 'above' : 'to ' + money(cap)} ${pct(rate)}`).join('; '));
  }
  L.push('');
  return L.join('\n');
}

const text = generate(loadRules());
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? norm(fs.readFileSync(OUT, 'utf8')) : '';
  if (have !== text) {
    console.error('docs/province-tax-rules.md is stale. Run: node scripts/gen-province-rules.js');
    process.exit(1);
  }
  console.log('province tax rules doc is current');
} else {
  fs.writeFileSync(OUT, text);
  console.log('wrote ' + path.relative(root, OUT));
}
